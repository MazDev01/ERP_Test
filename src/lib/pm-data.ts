/** รอข้อมูลเรื่องอะไร — รอลูกค้า · รอไฟล์ · อื่น ๆ (ป้ายอยู่ที่ task-deps WAIT_KIND_LABEL) */
export type WaitKind = "customer" | "file" | "other";

/** สถานะเปลี่ยนหนึ่งครั้ง — from = null คือตอนสร้าง/มอบหมายงาน · by = รหัสพนักงาน หรือ "ลูกค้า" */
export type StatusStep = { at: string; from: TaskStatus | null; to: TaskStatus; by: string };

/** รอบล่าสุดที่ส่งมา — ใช้ทั้งหน้างานรอตรวจและหน้างานที่ได้รับ */
export function lastSub(t: ProjectTask) {
  return t.subs?.[t.subs.length - 1];
}


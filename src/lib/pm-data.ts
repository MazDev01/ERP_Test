  clientReview?: boolean;
  /** ทุกครั้งที่สถานะเปลี่ยน เรียงเก่าไปใหม่ — ฐานของตัวเลขผลงานในอนาคต เขียนจากสโตร์ (withStatus) เท่านั้น */
  history?: StatusStep[];

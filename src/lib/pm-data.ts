  /** รหัสพนักงานของผู้สั่งงาน — PM เจ้าของโปรเจคตอนมอบหมาย · คนนี้คือผู้ตรวจด้วย */
  assignedBy?: string;
  /** ไม่ต้องตรวจ (งานเล็ก ความเสี่ยงต่ำ) — ส่งแล้วปิดงานทันที · ส่งให้ลูกค้าตรวจไม่ได้ */

/*
 * ขั้นของงานเข้าใหม่ (ผู้ใช้สั่ง 27 ต.ค. 2569)
 *   new  = รอ GM มอบหมาย PM
 *   plan = มี PM ดูแลแล้ว รอวางแผน (ยืนยันแผนแล้วออกจากกล่องไปเป็นโปรเจค)
 */
export type InboxStage = "new" | "plan";

/** งานนี้มี PM ดูแลแล้ว — ขั้น plan ที่มีชื่อ PM · ข้อมูลเก่าขั้น plan ที่ไม่มีชื่อถือว่ายังรอมอบหมาย (ผู้ใช้สั่ง 27 ต.ค. 2569) */
export function isAssignedJob(j: Pick<InboxJob, "stage" | "takenBy">) {
  return j.stage === "plan" && Boolean(j.takenBy);
}

/** งานที่ GM มอบหมายให้ PM คนนี้ (เทียบชื่อเต็ม รูปแบบเดียวกับ takenBy) */
export function isJobOf(j: Pick<InboxJob, "stage" | "takenBy">, pmName: string) {
  return isAssignedJob(j) && Boolean(pmName) && j.takenBy === pmName;
}

